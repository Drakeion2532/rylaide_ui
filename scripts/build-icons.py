"""Subset Material Symbols Rounded to the icons the app uses.

Scans web/**/*.js for quoted snake_case words, keeps the ones that are real icon names,
and writes web/fonts/symbols.woff2 (FILL axis kept; weight 400, grade 0, optical size 24)
plus web/js/icons.js mapping icon name -> codepoint.

Run: python3 scripts/build-icons.py
"""
import json
import pathlib
import re
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'node_modules/material-symbols/material-symbols-rounded.woff2'
OUT_FONT = ROOT / 'web/fonts/symbols.woff2'
OUT_MAP = ROOT / 'web/js/icons.js'

font = TTFont(SRC, lazy=False)
cmap = font.getBestCmap()
glyph_to_cp = {}
for cp, g in cmap.items():
    if cp >= 0xE000:
        glyph_to_cp.setdefault(g, cp)
# Glyphs are named after their icons (e.g. 'two_wheeler'); '.fill' variants are handled by the FILL axis.
names = {g: g for g in font.getGlyphOrder() if not g.startswith('.') and '.' not in g}
# Some icons share a glyph under another name (location_on -> place), so also read the ligature table.
glyph_to_char = {g: chr(cp) for cp, g in cmap.items() if cp < 0x80}
for lookup in font['GSUB'].table.LookupList.Lookup:
    for st in lookup.SubTable:
        st = getattr(st, 'ExtSubTable', st)
        for first, entries in (getattr(st, 'ligatures', None) or {}).items():
            for lig in entries:
                seq = [first, *lig.Component]
                if all(g in glyph_to_char for g in seq):
                    names.setdefault(''.join(glyph_to_char[g] for g in seq), lig.LigGlyph)

used = set()
for f in (ROOT / 'web').rglob('*.js'):
    if f.name == 'icons.js' or 'vendor' in f.parts:
        continue
    used.update(re.findall(r"""['"]([a-z][a-z0-9_]{1,40})['"]""", f.read_text()))

icons = {}
for n in sorted(used):
    g = names.get(n)
    if g and g in glyph_to_cp:
        icons[n] = glyph_to_cp[g]
missing = sorted(n for n in used if n in names and n not in icons)
if missing:
    print('no codepoint for:', missing, file=sys.stderr)

# Subset to the used codepoints first, then pin every axis except FILL.
opts = subset.Options()
opts.layout_features = []
opts.notdef_outline = True
opts.name_IDs = ['*']
sub = subset.Subsetter(options=opts)
sub.populate(unicodes=list(icons.values()))
sub.subset(font)
axes = {a.axisTag for a in font['fvar'].axes}
limits = {'wght': 400, 'GRAD': 0, 'opsz': 24}
font = instancer.instantiateVariableFont(font, {k: v for k, v in limits.items() if k in axes})
OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
font.flavor = 'woff2'
font.save(OUT_FONT)

OUT_MAP.write_text('// Generated by scripts/build-icons.py — icon name -> Material Symbols codepoint.\nexport const ICONS = ' + json.dumps(icons, indent=0, sort_keys=True).replace('\n', '') + ';\n')
print(f'{len(icons)} icons, {OUT_FONT.stat().st_size // 1024} KB -> {OUT_FONT.relative_to(ROOT)}')
